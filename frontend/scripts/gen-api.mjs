// Generate src/shared/api/schema.gen.ts from contracts/openapi.yaml.
// Until CT-01 lands the contract, write an empty schema so imports keep compiling.
import { execFileSync } from 'node:child_process'
import { existsSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const spec = path.resolve(root, '../contracts/openapi.yaml')
const out = path.resolve(root, 'src/shared/api/schema.gen.ts')

if (existsSync(spec)) {
  execFileSync('pnpm', ['exec', 'openapi-typescript', spec, '-o', out], {
    cwd: root,
    stdio: 'inherit',
  })
} else {
  console.warn(`contracts/openapi.yaml not found; writing empty schema to ${out}`)
  writeFileSync(
    out,
    [
      '// Generated by `pnpm gen:api` from contracts/openapi.yaml. Do not edit by hand.',
      '// Empty until CT-01 adds contracts/openapi.yaml.',
      'export type paths = Record<string, never>',
      'export type components = Record<string, never>',
      'export type operations = Record<string, never>',
      '',
    ].join('\n'),
  )
}
